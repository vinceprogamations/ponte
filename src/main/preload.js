'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (fn) => {
  const handler = (_e, payload) => fn(payload);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};

contextBridge.exposeInMainWorld('ponte', {
  init: () => ipcRenderer.invoke('init'),
  privacyStatus: () => ipcRenderer.invoke('privacy:status'),
  createPrivateInvite: () => ipcRenderer.invoke('privacy:invite'),
  acceptPrivateInvite: code => ipcRenderer.invoke('privacy:accept', code),
  approvePrivateDevice: pin => ipcRenderer.invoke('privacy:approve', pin),
  revokePrivateDevice: () => ipcRenderer.invoke('privacy:revoke'),
  onPrivacy: on('privacy'),
  onPrivateCallEnded: on('private-call-ended'),
  sendChat: (text) => ipcRenderer.invoke('chat:send', text),
  sendSignal: (to, data) => ipcRenderer.send('signal:send', { to, data }),
  setState: (patch) => ipcRenderer.send('state:set', patch),
  setName: (name) => ipcRenderer.invoke('name:set', name),
  addHost: (ip) => ipcRenderer.invoke('host:add', ip),
  removeHost: (ip) => ipcRenderer.invoke('host:remove', ip),
  screenSources: () => ipcRenderer.invoke('screen:sources'),
  selectScreen: (choice) => ipcRenderer.send('screen:select', choice),
  audioApps: () => ipcRenderer.invoke('audio:apps'),
  audioStart: (choice) => ipcRenderer.invoke('audio:start', choice),
  audioStop: () => ipcRenderer.send('audio:stop'),
  onAudioPcm: on('audio:pcm'),
  onAudioEnded: on('audio:ended'),
  editChat: (id, text) => ipcRenderer.invoke('chat:edit', { id, text }),
  deleteChat: (id) => ipcRenderer.invoke('chat:delete', id),
  reactChat: (id, emoji, on) => ipcRenderer.invoke('chat:react', { id, emoji, on }),
  typing: (channel) => ipcRenderer.send('chat:typing', channel),
  onChatUpdate: on('chat:update'),
  onTyping: on('typing'),
  onChannels: on('channels'),
  createChannel: (kind, name) => ipcRenderer.invoke('channels:create', { kind, name }),
  renameChannel: (id, name) => ipcRenderer.invoke('channels:rename', { id, name }),
  deleteChannel: (id) => ipcRenderer.invoke('channels:delete', id),
  openMedia: (id, reveal) => ipcRenderer.invoke('media:open', { id, reveal }),
  setPtt: (vk) => ipcRenderer.send('ptt:set', vk),
  onPtt: on('ptt'),
  onHotkey: on('hotkey'),
  onPresence: on('presence'),
  onRtt: on('rtt'),
  overlayUpdate: (data) => ipcRenderer.send('overlay:update', data),
  saveClip: (bytes, ext) => ipcRenderer.invoke('clip:save', { bytes, ext }),
  revealClip: (file) => ipcRenderer.send('clip:reveal', file),
  soundsList: () => ipcRenderer.invoke('sounds:list'),
  soundsGet: (id) => ipcRenderer.invoke('sounds:get', id),
  soundsAdd: (name, bytes) => ipcRenderer.invoke('sounds:add', { name, bytes }),
  soundsRemove: (id) => ipcRenderer.invoke('sounds:remove', id),
  sendMedia: (req) => ipcRenderer.invoke('media:send', req),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch { return ''; } },
  onMediaProgress: on('media:progress'),
  onMediaReady: on('media:ready'),
  log: (line) => ipcRenderer.send('log', String(line)),
  onPeers: on('peers'),
  onChat: on('chat'),
  onSignal: on('signal'),
  onLog: on('log'),
  onTrayCmd: on('tray:cmd'),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.send('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  onUpdate: on('update:status'),
});
